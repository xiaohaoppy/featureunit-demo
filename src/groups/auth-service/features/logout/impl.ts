import type { Logout } from "./contract";

export const logout: Logout = async ({ token }, { sessions, logger }) => {
  // 不变量 1（幂等）：delete 对不存在的 token 静默成功（端口语义），
  // 所以这里不需要先查再删——直接删，天然幂等。
  await sessions.delete(token);

  // 不变量 2：不记录 token 本身。
  logger.info("logout.ok");
};
