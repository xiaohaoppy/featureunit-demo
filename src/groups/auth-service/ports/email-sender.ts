/**
 * ============================================================================
 * [角色] 端口：EmailSender —— 邮件发送端口（冻结区）
 * ----------------------------------------------------------------------------
 * 一句话：单元只负责"决定要发一封什么主题、什么内容的信给谁"，
 *         发信的具体机制（SMTP / 日志 / 队列）是适配器的事。
 *
 * 设计要点：
 *   - text 是纯文本正文。HTML 模板、品牌样式属于【展示层】，不进业务单元；
 *     生产环境可在适配器里叠加模板渲染（或换成模板 ID + 参数的结构）。
 *   - 发送失败怎么办？由适配器决定（重试 / 投递队列），单元假定 send 成功或抛错。
 *
 * 谁可以改：只有人。AI 实现任务中禁止修改本文件。
 * ============================================================================
 */

/** 一封待发送邮件（纯数据）。 */
export interface EmailMessage {
  to: string;
  subject: string;
  text: string;
}

export interface EmailSender {
  /** 发送邮件。失败时抛错（由适配器决定是否重试）。 */
  send(message: EmailMessage): Promise<void>;
}
