/**
 * ============================================================================
 * [角色] 端口：RateLimiter —— 限流端口（冻结区）
 * ----------------------------------------------------------------------------
 * 一句话：把"这个操作是不是太频繁了"的判定抽象成端口。
 *
 * 为什么需要它：找回密码、登录是暴力破解的重灾区，必须限流。
 * 但限流的具体策略（固定窗口 / 滑动窗口 / 令牌桶、内存 / Redis）是
 * 适配器的事——单元只需要问一句"还允许吗？"。
 *
 * 语义约定：
 *   check(key) 会【消耗一次配额】并返回是否放行。
 *   调用方（单元）拿到 false 时应立即抛 RATE_LIMITED，不再执行后续业务。
 *
 * 谁可以改：只有人。AI 实现任务中禁止修改本文件。
 * ============================================================================
 */

export interface RateLimiter {
  /**
   * 检查并消耗一次配额。
   * @param key 限流维度，如 "reset:a@b.com"（单元负责拼 key，含业务前缀防冲突）
   * @returns true = 放行；false = 超限（应抛 RATE_LIMITED）
   */
  check(key: string): Promise<boolean>;
}
