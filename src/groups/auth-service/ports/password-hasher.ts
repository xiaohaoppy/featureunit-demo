/**
 * ============================================================================
 * [角色] 端口：PasswordHasher —— 密码哈希端口（冻结区）
 * ----------------------------------------------------------------------------
 * 一句话：单元只知道"hash(明文)→哈希"和"verify(明文, 哈希)→是否匹配"，
 *         完全不知道底层是 scrypt / argon2 / bcrypt。
 *
 * 为什么抽象成端口而不是让单元自己哈希：
 *   1. 哈希算法升级（scrypt → argon2）只改适配器，7 个单元零改动；
 *   2. 测试可以用真实适配器（本仓库的 ScryptPasswordHasher），
 *      也可以用假适配器（如恒返回固定值），判据更灵活；
 *   3. 防止 AI 写出"自己发明哈希"或"明文比较"的危险实现。
 *
 * 谁可以改：只有人。AI 实现任务中禁止修改本文件。
 * ============================================================================
 */

export interface PasswordHasher {
  /** 生成密码哈希（必须带随机盐，必须慢——防暴力破解）。 */
  hash(password: string): Promise<string>;
  /**
   * 校验明文与哈希是否匹配。
   * 注意：verify 的返回语义是"是否匹配"，不区分"用户不存在"。
   * 防枚举的职责在单元（用户不存在与密码错误返回同一错误码）。
   */
  verify(password: string, hash: string): Promise<boolean>;
}
